type CoreCopy = typeof enCore;
type Copy = CoreCopy & OpsCopy;
const keys = Object.keys(enCore).filter((k) => k !== 'roles') as (keyof Omit<
  CoreCopy,
  'roles'
>)[];
function translated(values: string[], roles: string[], ops: OpsCopy): Copy {
  if (values.length !== keys.length)
    throw new Error('Admin translation is incomplete');
  return {
    ...Object.fromEntries(keys.map((k, i) => [k, values[i]])),
    roles,
    ...ops,
  } as Copy;
}

