const keys = Object.keys(en).filter((k) => k !== 'roles') as (keyof Omit<
  Copy,
  'roles'
>)[];
function translated(values: string[], roles: string[]): Copy {
  if (values.length !== keys.length)
    throw new Error('Admin translation is incomplete');
  return {
    ...Object.fromEntries(keys.map((k, i) => [k, values[i]])),
    roles,
  } as Copy;
}
